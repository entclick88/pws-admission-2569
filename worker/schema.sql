DROP TABLE IF EXISTS records;
DROP TABLE IF EXISTS stages;
DROP TABLE IF EXISTS faqs;
DROP TABLE IF EXISTS announcements;
DROP TABLE IF EXISTS sessions;
DROP TABLE IF EXISTS users;

-- ── ผู้ดูแลระบบ (สร้างอัตโนมัติเมื่อ login ด้วย Google ครั้งแรก) ─────────────
CREATE TABLE users (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  email      TEXT UNIQUE NOT NULL,
  name       TEXT,
  picture    TEXT,
  role       TEXT NOT NULL DEFAULT 'admin',
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- ── session หลังเข้าสู่ระบบ (จดจำการเข้าสู่ระบบได้ 30 วัน) ───────────────────
CREATE TABLE sessions (
  token      TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX idx_sessions_user ON sessions (user_id);

-- ── ประกาศ / ข่าวสาร แสดงบนหน้าแรก ─────────────────────────────────────────
CREATE TABLE announcements (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  title      TEXT NOT NULL,
  body       TEXT NOT NULL,
  link_url   TEXT,
  link_label TEXT,
  published  INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- ── ฐานความรู้ chatbot ─────────────────────────────────────────────────────
-- keywords: คำสำคัญคั่นด้วย , — ยิ่งคำยาวและตรงมาก คะแนนยิ่งสูง
CREATE TABLE faqs (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  keywords   TEXT NOT NULL,
  question   TEXT NOT NULL,
  answer     TEXT NOT NULL,
  suggested  INTEGER NOT NULL DEFAULT 0,  -- 1 = แสดงเป็นปุ่มคำถามยอดฮิต
  sort_order INTEGER NOT NULL DEFAULT 0
);

-- ── รอบการประกาศ (คุมว่าเปิดให้สืบค้นได้หรือยัง) ────────────────────────────
CREATE TABLE stages (
  code         TEXT PRIMARY KEY,
  title        TEXT NOT NULL,
  published    INTEGER NOT NULL DEFAULT 0,
  publish_note TEXT,
  sort_order   INTEGER NOT NULL DEFAULT 0
);

-- ── ข้อมูลรายบุคคลของแต่ละรอบ (admin นำเข้าจาก CSV) ─────────────────────────
-- ผู้สมัครสืบค้นด้วยเลขประจำตัวประชาชน เห็นได้เฉพาะของตนเองเท่านั้น
CREATE TABLE records (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  stage       TEXT NOT NULL,
  citizen_id  TEXT NOT NULL,
  app_no      TEXT,
  full_name   TEXT,
  exam_type   TEXT,
  status      TEXT,        -- ผ่าน / ไม่ผ่าน / ผ่านเกณฑ์มาตรฐาน
  seat_no     TEXT,        -- เลขที่นั่งสอบ
  room        TEXT,        -- ห้องสอบ / ห้องสัมภาษณ์
  report_room TEXT,        -- ห้องรายงานตัว
  exam_date   TEXT,
  time_slot   TEXT,        -- ช่วงเวลาสอบ / เวลารายงานตัว
  score       TEXT,        -- คะแนน (Pre-Test)
  rank_no     TEXT,        -- ลำดับที่ (Pre-Test)
  note        TEXT,
  updated_at  TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE (stage, citizen_id)
);

CREATE INDEX idx_records_cid   ON records (citizen_id);
CREATE INDEX idx_records_stage ON records (stage);

